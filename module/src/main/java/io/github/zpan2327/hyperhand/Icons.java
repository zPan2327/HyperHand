    private static final float VB = 960f;
    private static final Path[] CACHE = new Path[PATHS.length];
    private static final float[] CACHE_SIZE = new float[PATHS.length];

    static void draw(Canvas canvas, int kind, float left, float top, float size, int color, float stroke) {
        if (kind < 0 || kind >= PATHS.length || size <= 0f) return;
        Paint paint = new Paint(Paint.ANTI_ALIAS_FLAG);
        paint.setStyle(Paint.Style.FILL);
        paint.setColor(color);
        float s = size / VB;
        canvas.save();
        canvas.translate(left, top);
        canvas.scale(s, s);
        canvas.translate(0f, VB);      // viewBox y: -960..0 → 画布 y: 0..960
        canvas.drawPath(path(kind, size), paint);
        canvas.restore();
    }

    /** 路径以 viewBox 原始坐标缓存，缩放交给 Canvas。 */
    private static Path path(int kind, float size) {
        synchronized (CACHE) {
            if (CACHE[kind] != null && CACHE_SIZE[kind] == size) return CACHE[kind];
            Path p = parse(PATHS[kind]);
            CACHE[kind] = p;
            CACHE_SIZE[kind] = size;
            return p;
        }
    }

    /** SVG path data → Path（viewBox 原始坐标）。支持 M/L/H/V/C/S/Q/T/Z，绝对与相对。 */
    private static Path parse(String d) {
        Path path = new Path();
        float[] n = new float[6];
        int i = 0, len = d.length();
        float cx = 0f, cy = 0f, sx = 0f, sy = 0f;
        float rx = 0f, ry = 0f;                 // 上一个三次/二次控制点（反射用）
        char cmd = 0;
        while (i < len) {
            char ch = d.charAt(i);
            if (Character.isWhitespace(ch) || ch == ',') { i++; continue; }
            if (Character.isLetter(ch)) { cmd = ch; i++; }
            boolean rel = Character.isLowerCase(cmd);
            switch (cmd) {
                case 'M': case 'm': {
                    i = num(d, i, n, 2);
                    cx = n[0] + (rel ? cx : 0f);
                    cy = n[1] + (rel ? cy : 0f);
                    path.moveTo(cx, cy);
                    sx = cx; sy = cy;
                    cmd = rel ? 'l' : 'L';      // 隐式后续 lineto
                    break;
                }
                case 'L': case 'l': {
                    i = num(d, i, n, 2);
                    cx = n[0] + (rel ? cx : 0f);
                    cy = n[1] + (rel ? cy : 0f);
                    path.lineTo(cx, cy);
                    break;
                }
                case 'H': case 'h': {
                    i = num(d, i, n, 1);
                    cx = n[0] + (rel ? cx : 0f);
                    path.lineTo(cx, cy);
                    break;
                }
                case 'V': case 'v': {
                    i = num(d, i, n, 1);
                    cy = n[0] + (rel ? cy : 0f);
                    path.lineTo(cx, cy);
                    break;
                }
                case 'C': case 'c': {
                    i = num(d, i, n, 6);
                    float x1 = n[0] + (rel ? cx : 0f), y1 = n[1] + (rel ? cy : 0f);
                    float x2 = n[2] + (rel ? cx : 0f), y2 = n[3] + (rel ? cy : 0f);
                    cx = n[4] + (rel ? cx : 0f); cy = n[5] + (rel ? cy : 0f);
                    path.cubicTo(x1, y1, x2, y2, cx, cy);
                    rx = x2; ry = y2;
                    break;
                }
                case 'S': case 's': {
                    i = num(d, i, n, 4);
                    float x1 = cx + cx - rx, y1 = cy + cy - ry;
                    float x2 = n[0] + (rel ? cx : 0f), y2 = n[1] + (rel ? cy : 0f);
                    cx = n[2] + (rel ? cx : 0f); cy = n[3] + (rel ? cy : 0f);
                    path.cubicTo(x1, y1, x2, y2, cx, cy);
                    rx = x2; ry = y2;
                    break;
                }
                case 'Q': case 'q': {
                    i = num(d, i, n, 4);
                    float x1 = n[0] + (rel ? cx : 0f), y1 = n[1] + (rel ? cy : 0f);
                    cx = n[2] + (rel ? cx : 0f); cy = n[3] + (rel ? cy : 0f);
                    path.quadTo(x1, y1, cx, cy);
                    rx = x1; ry = y1;
                    break;
                }
                case 'T': case 't': {
                    i = num(d, i, n, 2);
                    float x1 = cx + cx - rx, y1 = cy + cy - ry;
                    cx = n[0] + (rel ? cx : 0f); cy = n[1] + (rel ? cy : 0f);
                    path.quadTo(x1, y1, cx, cy);
                    rx = x1; ry = y1;
                    break;
                }
                case 'Z': case 'z': {
                    path.close();
                    cx = sx; cy = sy;
                    break;
                }
                default:
                    return path;
            }
        }
        return path;
    }

    /** 读 count 个数字：支持无分隔符（"10-20"）、小数、符号。 */
    private static int num(String d, int i, float[] out, int count) {
        int len = d.length();
        for (int k = 0; k < count; k++) {
            while (i < len && (Character.isWhitespace(d.charAt(i)) || d.charAt(i) == ',')) i++;
            int start = i;
            if (i < len && (d.charAt(i) == '-' || d.charAt(i) == '+')) i++;
            boolean dot = false;
            while (i < len) {
                char ch = d.charAt(i);
                if (ch >= '0' && ch <= '9') i++;
                else if (ch == '.' && !dot) { dot = true; i++; }
                else break;
            }
            out[k] = Float.parseFloat(d.substring(start, i));
        }
        return i;
    }

    static IconView view(Context c, int kind, float sizeDp, int color, float stroke) {
        return new IconView(c, kind, sizeDp, color);
    }

    static final class IconView extends View {
        private int kind;
        private int color;
        private final int sizePx;

        IconView(Context c, int kind, float sizeDp, int color) {
            super(c);
            this.kind = kind;
            this.color = color;
            sizePx = Theme.dp(c, Math.round(sizeDp));
            setLayoutParams(new android.view.ViewGroup.LayoutParams(sizePx, sizePx));
        }

        void setIconColor(int c) {
            color = c;
            invalidate();
        }

        @Override
        protected void onMeasure(int widthSpec, int heightSpec) {
            // 固有尺寸 = 图标像素；resolveSize 正确处理 EXACTLY/AT_MOST/UNSPECIFIED，
            // 不会像 getDefaultSize 那样在 AT_MOST 下吞掉整个可用宽度。
            setMeasuredDimension(
                    resolveSize(sizePx, widthSpec),
                    resolveSize(sizePx, heightSpec));
        }

        @Override
        protected void onDraw(Canvas canvas) {
            float size = Math.min(getWidth(), getHeight());
            float x = (getWidth() - size) / 2f;
            float y = (getHeight() - size) / 2f;
            Icons.draw(canvas, kind, x, y, size, color, 0f);
        }
    }
